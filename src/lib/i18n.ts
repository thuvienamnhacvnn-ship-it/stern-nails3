/**
 * German is the site; English is the same site with the strings swapped.
 *
 * The dictionary is one object per locale with the same shape, checked by the
 * type of `de` — so an English string that goes missing is a build error rather
 * than a German word appearing on the English page.
 *
 * Content that belongs to the studio (service names, look descriptions, legal
 * text) is not here. It lives in the database with a `…De` and a `…En` column,
 * because the owner has to be able to change it without a deploy.
 */

export const LOCALES = ['de', 'en'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'de';

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

/**
 * Route segments are translated too, so `/en/looks` never shows a German word
 * in the address bar. The keys are the internal page names.
 */
